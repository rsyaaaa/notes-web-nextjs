// Run: node --test tests/account-deletion-database.test.mjs
// Requires non-root execution and PostgreSQL binaries in /usr/bin. No npm driver,
// Supabase instance, .env files, inherited PG settings, or network access is used.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const migrations = join(root, 'supabase/migrations')
const target = '20261029000100_account_deletion_and_note_notices.sql'
const owner = '00000000-0000-4000-8000-000000000001'
const recipient = '00000000-0000-4000-8000-000000000002'
const secondRecipient = '00000000-0000-4000-8000-000000000003'
const outsider = '00000000-0000-4000-8000-000000000004'

// The original base notes/auth schema is not in the migration history. Supply
// only its required columns, constraints, RLS, and Supabase API role grants;
// profiles/folders/members and all their actual policies come from migrations.
const bootstrap = `
  create role anon nologin;
  create role authenticated nologin;
  create role service_role nologin bypassrls;
  create schema auth;
  create table auth.users (
    id uuid primary key,
    email text,
    raw_user_meta_data jsonb not null default '{}'
  );
  create function auth.uid() returns uuid language sql stable as $$
    select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
  $$;
  create function auth.role() returns text language sql stable as $$
    select nullif(current_setting('request.jwt.claim.role', true), '')
  $$;
  grant usage on schema public, auth to anon, authenticated, service_role;
  grant execute on function auth.uid(), auth.role() to anon, authenticated, service_role;
  alter default privileges in schema public
    grant all on tables to anon, authenticated, service_role;
  alter default privileges in schema public
    grant usage, select on sequences to anon, authenticated, service_role;
  create table public.notes (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    title text not null default '',
    content text not null default '',
    is_pinned boolean not null default false,
    is_trashed boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
  );
  alter table public.notes enable row level security;
  create publication supabase_realtime;

  -- Unrelated Supabase schemas are only stubs needed to replay prior SQL.
  create schema realtime;
  create table realtime.messages (extension text);
  alter table realtime.messages enable row level security;
  create function realtime.topic() returns text language sql stable as $$
    select current_setting('realtime.topic', true)
  $$;
  create schema storage;
  create table storage.buckets (id text primary key, name text, public boolean);
  create table storage.objects (bucket_id text, name text);
  alter table storage.objects enable row level security;
  create function storage.foldername(text) returns text[] language sql immutable as $$
    select string_to_array($1, '/')
  $$;
`

