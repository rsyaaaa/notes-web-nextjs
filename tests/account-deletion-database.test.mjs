function asUser(user, role = 'authenticated') {
  return `set local role ${role};
    set local "request.jwt.claim.sub" = '${user}';
    set local "request.jwt.claim.role" = '${role}';`
}

function check(expression, message) {
  return `do $$ begin
    if (${expression}) is not true then
      raise exception '%', '${message.replaceAll("'", "''")}';
    end if;
  end $$;`
}

test('account deletion migration against isolated PostgreSQL', { timeout: 120_000 }, async (t) => {
  assert.notEqual(process.getuid?.(), 0, 'initdb must run as a non-root user')
  const temporary = mkdtempSync('/tmp/notes-account-deletion-')
  const data = join(temporary, 'data')
  const log = join(temporary, 'postgres.log')
  // Explicit environment prevents PGHOST/PGSERVICE/PGPASSWORD/etc. from ever
  // directing psql at a real database or reading a user's connection files.
  const env = { PATH: '/usr/bin:/bin', HOME: temporary, LC_ALL: 'C', TZ: 'UTC' }
  let initialized = false

  function command(binary, args, input, timeout = 15_000) {
    const result = spawnSync(`/usr/bin/${binary}`, args, {
      input, encoding: 'utf8', env, timeout, maxBuffer: 4 * 1024 * 1024,
    })
    assert.ifError(result.error)
    return result
  }

  function succeed(result, context) {
    assert.equal(result.status, 0, `${context}\n${result.stderr}\n${result.stdout}`)
    return result.stdout.trim()
  }

  function psql(sql) {
    return command('psql', [
      '-X', '--no-password', '--host', temporary, '--port', '5432',
      '--username', 'postgres', '--dbname', 'postgres',
      '--quiet', '--tuples-only', '--no-align',
      '--set', 'ON_ERROR_STOP=1', '--set', 'VERBOSITY=verbose',
    ], sql)
  }

  function run(sql) {
    return succeed(psql(sql), 'SQL failed')
  }

  function transaction(sql) {
    return run(`begin; ${sql}\nrollback;`)
  }

  function denied(sql, state = '42501') {
    const result = psql(`begin; ${sql}`)
    assert.equal(result.status, 3, `Expected SQL rejection, got ${result.status}\n${result.stderr}`)
    assert.match(result.stderr, new RegExp(`ERROR:  ${state}:`))
    // A failed psql connection closes its open transaction, rolling it back.
  }

  try {
    succeed(command('initdb', [
      '-D', data, '--username=postgres', '--auth-local=trust',
      '--auth-host=reject', '--encoding=UTF8', '--no-locale', '--no-sync',
    ]), 'initdb failed')
    initialized = true
    succeed(command('pg_ctl', [
      '-D', data, '-l', log, '-w', '-t', '15', '-o',
      `-c listen_addresses='' -c unix_socket_directories='${temporary}' -c unix_socket_permissions=0700 -c wal_level=logical -c max_connections=10 -c fsync=off`,
      'start',
    ], undefined, 20_000), `PostgreSQL startup failed${existsSync(log) ? `\n${readFileSync(log, 'utf8')}` : ''}`)

    run(bootstrap)
    for (const file of readdirSync(migrations).filter((name) => name.endsWith('.sql') && name < target).sort()) {
      succeed(psql(readFileSync(join(migrations, file), 'utf8')), `Prior migration ${file} failed`)
    }
    run(fixtures)
    succeed(psql(readFileSync(join(migrations, target), 'utf8')), `Migration ${target} failed`)

    await t.test('backfills existing trash with metadata only and registers realtime', () => {
      assert.deepEqual(JSON.parse(run(`
        select json_agg(column_name order by ordinal_position)
        from information_schema.columns
        where table_schema = 'public' and table_name = 'note_deletion_notices';
      `)), ['id', 'note_id', 'user_id', 'deleted_at'])
      run(check(`(select count(*) = 1 from public.note_deletion_notices
        where note_id = 108 and user_id = '${recipient}' and deleted_at = '2026-01-01T00:00:00Z')`, 'Backfill missing or timestamp changed'))
      run(check(`exists (select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'note_deletion_notices')`, 'Realtime publication missing'))
      assert.equal(run('show listen_addresses;'), '')
      assert.equal(run('show unix_socket_directories;'), temporary)
    })

    await t.test('hard delete notifies every collaborator, never owner, without retaining private data', () => {
      const notices = JSON.parse(transaction(`
        ${asUser(owner)}
        delete from public.notes where id = 101;
        reset role;
        ${check('not exists (select 1 from public.notes where id = 101)', 'Note survived delete')}
        ${check('not exists (select 1 from public.note_members where note_id = 101)', 'Membership cascade failed')}
        ${check(`not exists (select 1 from public.note_deletion_notices where note_id = 101 and user_id = '${owner}')`, 'Owner was notified')}
        select json_agg(n order by user_id) from public.note_deletion_notices n where note_id = 101;
      `))
      assert.equal(notices.length, 2)
      assert.deepEqual(notices.map((notice) => notice.user_id), [recipient, secondRecipient])
      for (const notice of notices) {
        assert.deepEqual(Object.keys(notice).sort(), ['deleted_at', 'id', 'note_id', 'user_id'])
        assert.equal(notice.note_id, 101)
        assert.match(notice.id, /^[0-9a-f-]{36}$/)
        assert.ok(Number.isFinite(Date.parse(notice.deleted_at)))
      }
      assert.doesNotMatch(JSON.stringify(notices), /Private|example\.invalid|Unshared/)
      transaction(`
        ${asUser(owner)} delete from public.notes where id = 103; reset role;
        ${check('not exists (select 1 from public.note_deletion_notices where note_id = 103)', 'Unshared note created a notice')}
      `)
    })

    await t.test('trash revokes collaborator reads, edits, membership and presence access; restore reverses it', () => {
      transaction(`
        ${asUser(recipient)}
        ${check('public.can_access_note(102)', 'Collaborator initially has no access')}
        ${check('exists (select 1 from public.notes where id = 102)', 'Initial RLS read failed')}
        set local "realtime.topic" = 'notes:102';
        ${check('public.can_access_note_topic()', 'Initial presence access failed')}
        update public.notes set content = 'Collaborative edit' where id = 102;
        ${asUser(owner)} update public.notes set is_trashed = true where id = 102;
        ${check('public.can_access_note(102)', 'Owner lost trash access')}
        ${check('exists (select 1 from public.notes where id = 102 and is_trashed)', 'Owner cannot read trash')}
        ${asUser(recipient)}
        ${check('not public.can_access_note(102)', 'Trashed note still accessible')}
        ${check('not public.can_access_note_topic()', 'Trashed presence still accessible')}
        ${check('not exists (select 1 from public.notes where id = 102)', 'RLS exposes trash')}
        ${check('not exists (select 1 from public.note_members where note_id = 102)', 'RLS exposes trashed membership')}
        ${check('exists (select 1 from public.note_deletion_notices where note_id = 102)', 'Trash notice missing')}
        with edited as (update public.notes set content = 'Stale-tab attack' where id = 102 returning id)
          select 1 / case when count(*) = 0 then 1 else 0 end from edited;
        ${asUser(owner)} update public.notes set is_trashed = false where id = 102;
        ${asUser(recipient)}
        ${check('public.can_access_note(102) and public.can_access_note_topic()', 'Restore did not restore access')}
        ${check("exists (select 1 from public.notes where id = 102 and content = 'Collaborative edit')", 'Stale edit changed content')}
        ${check('not exists (select 1 from public.note_deletion_notices where note_id = 102)', 'Stale notice survived restore')}
        update public.notes set content = 'Restored collaborative edit' where id = 102;
        ${check("exists (select 1 from public.notes where id = 102 and content = 'Restored collaborative edit')", 'Restored edit failed')}
      `)
      denied(`${asUser(recipient)} update public.notes set is_trashed = true where id = 102;`, 'P0001')
    })

    await t.test('repeated trash/delete events upsert a single notice per recipient', () => {
      transaction(`
        ${asUser(owner)} update public.notes set is_trashed = true where id = 101;
        reset role;
        update public.note_deletion_notices set deleted_at = '2000-01-01' where note_id = 101;
        ${asUser(owner)} delete from public.notes where id = 101;
        reset role;
        ${check(`(select count(*) = 2 and bool_and(deleted_at > '2000-01-01')
          from public.note_deletion_notices where note_id = 101)`, 'Hard-delete upsert failed')}
        ${asUser(recipient)}
        ${check('not public.can_access_note(101)', 'Deleted note access survived')}
      `)
    })

    await t.test('auth deletion cleans owned data and invited_by references but preserves other notes', () => {
      transaction(`
        -- The BEFORE auth trigger must run before either FK cascade can erase recipients.
        delete from auth.users where id = '${owner}';
        ${check(`not exists (select 1 from auth.users where id = '${owner}')`, 'Auth user survived')}
        ${check(`not exists (select 1 from public.profiles where id = '${owner}')`, 'Profile survived')}
        ${check(`not exists (select 1 from public.note_folders where user_id = '${owner}')`, 'Folder survived')}
        ${check(`not exists (select 1 from public.notes where user_id = '${owner}')`, 'Owned notes survived')}
        ${check(`not exists (select 1 from public.note_members where user_id = '${owner}' or invited_by = '${owner}')`, 'Membership or invited_by survived')}
        ${check(`(select array_agg(id order by id) = array[104,105,106,107]::bigint[] from public.notes)`, 'Other notes were deleted')}
        ${check(`(select count(*) = 3 from public.profiles)`, 'Other profiles changed')}
        ${check(`exists (select 1 from public.note_folders where id = 22)`, 'Other folder deleted')}
        ${check(`(select count(*) = 2 from public.note_members)`, 'Unrelated memberships changed')}
        ${check(`exists (select 1 from public.note_members where note_id = 104 and user_id = '${secondRecipient}')`, 'Other shared membership deleted')}
        ${check(`exists (select 1 from public.note_members where note_id = 106 and user_id = '${secondRecipient}')`, 'Other collaborator deleted')}
        ${check(`(select count(*) = 4 from public.note_deletion_notices)`, 'Expected four surviving recipient notices')}
        ${check(`not exists (select 1 from public.note_deletion_notices where user_id = '${owner}' or note_id in (103,104,105,106,107))`, 'Unexpected notice recipient or note')}
        ${asUser(recipient)}
        ${check('(select count(*) = 3 from public.note_deletion_notices)', 'Recipient notices missing after owner deletion')}
        ${check('not public.can_access_note(101)', 'Deleted owner note accessible')}
        ${check('public.can_access_note(104)', 'Other owner lost access')}
        reset role;
        delete from auth.users where id = '${recipient}';
        ${check(`not exists (select 1 from public.note_deletion_notices where user_id = '${recipient}')`, 'Recipient notices did not cascade')}
      `)
    })

    await t.test('notice RLS isolates recipients, and clients cannot insert/update/delete/truncate', () => {
      transaction(`
        ${asUser(owner)} delete from public.notes where id = 101;
        ${asUser(recipient)}
        ${check('(select count(*) = 2 from public.note_deletion_notices)', 'Own notice count wrong')}
        ${check(`not exists (select 1 from public.note_deletion_notices where user_id <> '${recipient}')`, 'Recipient sees another user')}
        ${asUser(secondRecipient)}
        ${check('(select count(*) = 1 from public.note_deletion_notices)', 'Second recipient notice count wrong')}
        ${asUser(outsider)}
        ${check('not exists (select 1 from public.note_deletion_notices)', 'Outsider can see notices')}
        ${check('not public.can_access_note(102)', 'Outsider can access shared note')}
        ${asUser('', 'service_role')}
        ${check('(select count(*) = 3 from public.note_deletion_notices)', 'Service role cannot see all notices')}
      `)
      for (const role of ['anon', 'authenticated']) {
        const identity = asUser(recipient, role)
        for (const statement of [
          `insert into public.note_deletion_notices (note_id, user_id) values (999, '${recipient}')`,
          `update public.note_deletion_notices set deleted_at = now() where note_id = 108`,
          'delete from public.note_deletion_notices where note_id = 108',
          'truncate public.note_deletion_notices',
        ]) denied(`${identity} ${statement};`)
        if (role === 'anon') denied(`${identity} select * from public.note_deletion_notices;`)
      }
      transaction(`
        ${asUser(recipient)} set local "request.jwt.claim.sub" = '';
        ${check('not exists (select 1 from public.note_deletion_notices)', 'Missing JWT exposed notices')}
      `)
    })

    await t.test('explicit rollback restores auth, notes, memberships, folders, profiles and notices', () => {
      const snapshot = () => JSON.parse(run(`select json_build_object(
        'users', (select jsonb_agg(x order by id) from auth.users x),
        'profiles', (select jsonb_agg(x order by id) from public.profiles x),
        'folders', (select jsonb_agg(x order by id) from public.note_folders x),
        'notes', (select jsonb_agg(x order by id) from public.notes x),
        'members', (select jsonb_agg(x order by note_id, user_id) from public.note_members x),
        'notices', (select jsonb_agg(x order by id) from public.note_deletion_notices x)
      );`))
      const before = snapshot()
      transaction(`
        delete from auth.users where id = '${owner}';
        ${check(`not exists (select 1 from auth.users where id = '${owner}')`, 'Delete did not execute before rollback')}
        ${check('exists (select 1 from public.note_deletion_notices where note_id = 101)', 'Notice did not execute before rollback')}
      `)
      assert.deepEqual(snapshot(), before)
      transaction(`${asUser(owner)} update public.notes set is_trashed = true where id = 102;`)
      assert.deepEqual(snapshot(), before)
      // An error after cleanup must abort the entire deletion, not leave partial cleanup.
      denied(`delete from auth.users where id = '${owner}'; select 1 / 0;`, '22012')
      assert.deepEqual(snapshot(), before)
    })

    await t.test('readiness is service-only, trigger functions are not client RPCs, disabled/missing triggers fail closed', () => {
      assert.equal(transaction(`${asUser('', 'service_role')} select public.account_deletion_ready();`), 't')
      for (const role of ['anon', 'authenticated']) {
        denied(`${asUser(owner, role)} select public.account_deletion_ready();`)
        for (const functionName of ['record_note_deletion_notice', 'cleanup_deleted_account']) {
          denied(`${asUser(owner, role)} select public.${functionName}();`)
        }
      }
      run(check(`not has_function_privilege('anon', 'public.can_access_note(bigint)', 'EXECUTE')
        and has_function_privilege('authenticated', 'public.can_access_note(bigint)', 'EXECUTE')`, 'Access helper permissions wrong'))
      for (const [table, trigger] of [
        ['auth.users', 'cleanup_account_before_auth_delete'],
        ['public.notes', 'record_note_deletion_before_delete'],
        ['public.notes', 'record_note_deletion_on_trash'],
      ]) {
        assert.equal(transaction(`alter table ${table} disable trigger ${trigger};
          ${asUser('', 'service_role')} select public.account_deletion_ready();`), 'f')
        assert.equal(transaction(`drop trigger ${trigger} on ${table};
          ${asUser('', 'service_role')} select public.account_deletion_ready();`), 'f')
      }
      assert.equal(transaction(`drop table public.note_deletion_notices;
        ${asUser('', 'service_role')} select public.account_deletion_ready();`), 'f')
      assert.equal(transaction(`${asUser('', 'service_role')} select public.account_deletion_ready();`), 't')
    })
  } finally {
    // Also stop a partially started server if startup or any assertion fails.
    try {
      if (initialized && existsSync(join(data, 'postmaster.pid'))) {
        succeed(command('pg_ctl', ['-D', data, '-m', 'immediate', '-w', '-t', '15', 'stop'], undefined, 20_000), 'PostgreSQL teardown failed')
      }
    } finally {
      rmSync(temporary, { recursive: true, force: true })
    }
  }
})
