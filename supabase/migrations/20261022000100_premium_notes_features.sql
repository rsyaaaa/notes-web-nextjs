drop policy if exists "Users can view their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can view profiles in shared notes"
  on public.profiles for select to authenticated
  using (
    id = (select auth.uid())
    or exists (
      select 1
      from public.note_members mine
      join public.note_members theirs on theirs.note_id = mine.note_id
      where mine.user_id = (select auth.uid()) and theirs.user_id = profiles.id
    )
    or exists (
      select 1 from public.notes n
      join public.note_members m on m.note_id = n.id
      where n.user_id = (select auth.uid()) and m.user_id = profiles.id
    )
  );
revoke update on public.profiles from authenticated;
grant update (full_name, avatar_url) on public.profiles to authenticated;
create policy "Users can update editable profile fields"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

