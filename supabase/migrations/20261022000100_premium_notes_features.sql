create or replace function public.is_premium_user(target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = target_user_id and plan = 'premium'
  );
$$;

create or replace function public.can_access_note(target_note_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.notes n
    where n.id = target_note_id
      and (n.user_id = (select auth.uid()) or exists (
        select 1 from public.note_members m
        where m.note_id = n.id and m.user_id = (select auth.uid())
      ))
  );
$$;

create or replace function public.can_access_note_topic()
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  target_note_id bigint;
begin
  if realtime.topic() !~ '^notes:[0-9]+$' then
    return false;
  end if;
  target_note_id := split_part(realtime.topic(), ':', 2)::bigint;
  return public.can_access_note(target_note_id);
end;
$$;

create or replace function public.keep_note_owner_unchanged()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.user_id is distinct from old.user_id then
    raise exception 'Note owner cannot be changed';
  end if;
  return new;
end;
$$;

drop trigger if exists keep_note_owner_unchanged on public.notes;
create trigger keep_note_owner_unchanged
  before update on public.notes
  for each row execute function public.keep_note_owner_unchanged();

create or replace function public.validate_note_folder_owner()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.folder_id is not null and not exists (
    select 1 from public.note_folders f
    where f.id = new.folder_id and f.user_id = new.user_id
  ) then
    raise exception 'Folder must belong to the note owner';
  end if;
  return new;
end;
$$;

drop trigger if exists validate_note_folder_owner on public.notes;
create trigger validate_note_folder_owner
  before insert or update of folder_id, user_id on public.notes
  for each row execute function public.validate_note_folder_owner();

create or replace function public.enforce_free_note_pin_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_pins integer;
begin
  if not new.is_pinned or public.is_premium_user(new.user_id) then
    return new;
  end if;

  perform pg_advisory_xact_lock(hashtextextended(new.user_id::text, 0));
  select count(*) into current_pins
  from public.notes n
  where n.user_id = new.user_id
    and n.is_pinned
    and (tg_op = 'INSERT' or n.id <> new.id);

  if current_pins >= 3 then
    raise exception 'Free plan allows up to 3 pinned notes' using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_free_note_pin_limit on public.notes;
create trigger enforce_free_note_pin_limit
  before insert or update of is_pinned on public.notes
  for each row execute function public.enforce_free_note_pin_limit();

create or replace function public.invite_note_collaborator(target_note_id bigint, collaborator_email text)
returns table (user_id uuid, full_name text, avatar_url text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  note_owner uuid;
  invited_user uuid;
begin
  select n.user_id into note_owner
  from public.notes n
  where n.id = target_note_id;

  if note_owner is null or note_owner <> (select auth.uid()) then
    raise exception 'Only the note owner can invite collaborators';
  end if;
  if not public.is_premium_user(note_owner) then
    raise exception 'Premium plan is required to share notes';
  end if;

  select u.id into invited_user
  from auth.users u
  where lower(u.email) = lower(trim(collaborator_email));

  if invited_user is null then
    raise exception 'No account found for that email';
  end if;
  if invited_user = note_owner then
    raise exception 'You already own this note';
  end if;

  insert into public.note_members (note_id, user_id, invited_by)
  values (target_note_id, invited_user, note_owner)
  on conflict (note_id, user_id) do nothing;

  return query
  select p.id, p.full_name, p.avatar_url
  from public.profiles p where p.id = invited_user;
end;
$$;

